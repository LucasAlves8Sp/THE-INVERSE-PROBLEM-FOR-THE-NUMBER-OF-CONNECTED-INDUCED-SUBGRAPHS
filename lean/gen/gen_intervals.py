"""Generate ConnectedSets/Intervals.lean: the intervals of Lemma 4.4 used in Theorem 4.6."""
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'ConnectedSets', 'Intervals.lean')
specs = [
    # name, kind (V/L), m, lo, hi (inclusive), excluded
    ("G6", "V", 6, 32, 63, []),
    ("G7", "V", 7, 64, 127, []),
    ("H7", "L", 7, 7, 127, []),
    ("V5I", "V", 5, 17, 31, [25]),
    ("L4I", "L", 4, 10, 15, []),
    ("L5I", "L", 5, 21, 31, [25]),
    ("L6I", "L", 6, 53, 62, []),
]
lines = ["/-", "ConnectedSets/Intervals.lean  (generated by gen/gen_intervals.py)", "",
         "Interval forms of the base facts of Lemma 4.4.", "-/",
         "import ConnectedSets.Base", "", "namespace ConnectedSets", ""]
for name, kind, m, lo, hi, exc in specs:
    pred = "InV" if kind == "V" else "InLam"
    prefix = "V" if kind == "V" else "L"
    hyp_exc = "".join(f" → v ≠ {e}" for e in exc)
    lines.append(f"theorem {name} : ∀ v, {lo} ≤ v → v ≤ {hi}{hyp_exc} → {pred} {m} v := by")
    names = " ".join(f"h{e}" for e in exc)
    lines.append(f"  intro v hlo hhi {names}".rstrip())
    lines.append("  interval_cases v")
    items = []
    for v in range(lo, hi + 1):
        if v in exc:
            items.append(f"absurd rfl h{v}")
        else:
            items.append(f"{prefix}_{m}_{v}")
    lines.append("  exacts [" + ", ".join(items) + "]")
    lines.append("")
lines += ["end ConnectedSets", ""]
open(OUT, 'w').write("\n".join(lines))
print("ok")
