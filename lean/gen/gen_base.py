"""Generate ConnectedSets/Sporadic.lean and ConnectedSets/Base.lean from the supplement:
the sporadic graphs of construct.py and the derivations of data/base_certificate.txt."""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
# layout of the repository: <root>/lean/gen/this_file, <root>/code, <root>/data
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, os.path.join(ROOT, 'code'))
from construct import SPORADIC

OUT = os.path.join(HERE, '..', 'ConnectedSets')

# ---------------------------------------------------------------- sporadic graphs
lines = ["/-",
         "ConnectedSets/Sporadic.lean  (generated by gen/gen_base.py from code/construct.py)",
         "",
         "The seven sporadic graphs of Table 1, given by neighbourhood masks; their connectivity",
         "and their counts are checked by the kernel through the verified checker.",
         "-/",
         "import ConnectedSets.Checker", "", "namespace ConnectedSets", ""]
for val, (n, edges, desc, hand) in sorted(SPORADIC.items()):
    masks = [0] * n
    for a, b in edges:
        masks[a] |= 1 << b
        masks[b] |= 1 << a
    ml = ", ".join(map(str, masks))
    lines += [f"/-- Sporadic graph for {val} on {n} vertices: {desc}. Edges: "
              + " ".join(f"{a}{b}" for a, b in edges) + ". -/",
              f"def sporadicMasks{val} : ℕ → ℕ := fun i => [{ml}].getD i 0", "",
              f"theorem sporadic_{val} : InV {n} {val} :=",
              f"  inV_of_masks sporadicMasks{val} (by decide +kernel) (by decide +kernel) "
              f"(by decide +kernel) (by decide +kernel)", ""]
lines += ["end ConnectedSets", ""]
open(os.path.join(OUT, 'Sporadic.lean'), 'w').write("\n".join(lines))

# ---------------------------------------------------------------- base derivations
cert = open(os.path.join(ROOT, 'data', 'base_certificate.txt')).read().splitlines()
out = ["/-",
       "ConnectedSets/Base.lean  (generated by gen/gen_base.py from data/base_certificate.txt)",
       "",
       "Lemma 4.4 of the paper: each value of V_m and Λ_m for m ≤ 7 is derived by one of the",
       "rules (U), (C), (N), a sporadic graph, or the one-vertex graph, exactly as in the",
       "certificate of the supplementary material.",
       "-/",
       "import ConnectedSets.Sporadic", "", "namespace ConnectedSets", "",
       "theorem L_0_0 : InLam 0 0 := inLam_zero", ""]
count = 0
for line in cert:
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    head, der = line.split(':')
    mpart, kind, val = head.split()
    m = int(mpart[2:]); v = int(val)
    tok = der.split()
    if kind == 'V':
        name = f"V_{m}_{v}"
        if tok[0] == 'single':
            body = "inV_one"
        elif tok[0] == 'S':
            body = f"sporadic_{v}"
        elif tok[0] == 'C':
            x = int(tok[1])
            body = f"ruleC L_{m-1}_{x} (by norm_num) (by norm_num)"
        elif tok[0] == 'N':
            d, r, x = map(int, tok[1:])
            body = f"ruleN (d := {d}) L_{r}_{x} (by norm_num) (by norm_num) (by norm_num)"
        out.append(f"theorem {name} : InV {m} {v} := {body}")
    else:
        name = f"L_{m}_{v}"
        if tok[0] == 'V':
            body = f"V_{m}_{v}.inLam"
        else:
            a, x, y = map(int, tok[1:])
            body = f"ruleU V_{a}_{x} L_{m-a}_{y} (by norm_num) (by norm_num)"
        out.append(f"theorem {name} : InLam {m} {v} := {body}")
    count += 1
out += ["", "end ConnectedSets", ""]
open(os.path.join(OUT, 'Base.lean'), 'w').write("\n".join(out))
print("sporadic graphs:", len(SPORADIC), " base derivations:", count)
